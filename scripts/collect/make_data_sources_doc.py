"""Regenerate docs/data_sources.md from the latest manifests.

    python scripts/collect/make_data_sources_doc.py [--out DIR]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from collect_all import SOURCES  # noqa: E402
from collect_common import default_out_dir  # noqa: E402

HEAD = """# External data sources (work package B1)

Generated by `python scripts/collect/make_data_sources_doc.py` from the manifests written by
`python scripts/collect/collect_all.py`. Downloaded data lives in `data/sources/` (gitignored, never committed):

    data/sources/<source>/<YYYY-MM-DD>/{raw/, records.jsonl, manifest.json}
    data/sources/<source>/LATEST

Roles enforce the leakage firewall of the retrieval plan (section 6.1): a `query` source may only write benchmark
queries, an `expansion` source may only enrich documents (aliases, PoC index), an `incident` source feeds narrative
(T0) queries, an `attack` source is ingested as content. No source has two roles.

| Source | Role | Status | Records | Licence | Upstream | Retrieved (UTC) |
|---|---|---|---|---|---|---|
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=default_out_dir())
    a = ap.parse_args()
    rows, notes = [], []
    for name in SOURCES:
        lf = a.out / name / "LATEST"
        if not lf.exists():
            rows.append(f"| {name} | - | not collected | - | - | - | - |")
            continue
        m = json.loads((a.out / name / lf.read_text().strip() / "manifest.json").read_text(encoding="utf-8"))
        lic = m["license"]
        url = m["upstream_urls"][0]
        ver = m.get("upstream_version") or {}
        rows.append(f"| `{name}` | {m['role']} | {m['status']} | {m['record_count']:,} | "
                    f"[{lic['name']}]({lic['url']}) | <{url}> | {m['retrieved_at_utc']} |")
        v = ", ".join(f"{k}={str(val)[:12] if k == 'commit' else val}" for k, val in ver.items()
                      if k in ("commit", "attack_version", "kev_version", "ruleset"))
        extra = []
        if m["status"] != "ok":
            extra.append(f"**{m['status']}**: {m['reason']}")
        extra.append(lic["permits"])
        if m.get("malformed_cve_ids_dropped"):
            extra.append(f"{m['malformed_cve_ids_dropped']} malformed CVE ids dropped")
        notes.append(f"- `{name}` ({v or 'no version'}): " + " ".join(extra))
    text = HEAD + "\n".join(rows) + "\n\n## Licence notes and provenance\n\n" + "\n".join(notes) + "\n"
    dest = Path(__file__).resolve().parents[2] / "docs" / "data_sources.md"
    dest.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
